import { Router } from 'express';
import { policy } from '../config/permissions';
import { appointmentController } from '../controllers/appointmentController';
import { attendanceController } from '../controllers/attendanceController';
import { expenseController } from '../controllers/expenseController';
import { operationsController } from '../controllers/operationsController';
import { reportController } from '../controllers/reportController';
import { resourceController } from '../controllers/resourceController';
import { settingsController } from '../controllers/settingsController';
import { authMiddleware, requireOwnStaffDataOr, requireRole } from '../middleware/authMiddleware';
import { uuidParam } from '../middleware/validateParams';

const router = Router();
const manageStaff = requireRole(policy.manageStaff);
const manageCatalog = requireRole(policy.manageCatalog);

router.use(authMiddleware);
for (const name of ['id', 'staffId', 'serviceId', 'productId']) router.param(name, uuidParam);
router.get('/settings', settingsController.get);
router.put('/settings', requireRole(policy.manageSettings), settingsController.update);
router.get('/staff', resourceController.listStaff);
router.post('/staff', manageStaff, resourceController.createStaff);
router.patch('/staff/:id', manageStaff, resourceController.updateStaff);
router.delete('/staff/:id', manageStaff, resourceController.deleteStaff);
router.post('/staff/:id/restore', manageStaff, resourceController.restoreStaff);
router.get('/expenses', expenseController.list);
router.post('/expenses', expenseController.create);
router.post('/expenses/:id/cancel', requireRole(policy.deleteExpenses), expenseController.cancel);
router.delete('/expenses/:id', requireRole(policy.deleteExpenses), expenseController.cancel);
router.get('/attendance', attendanceController.listForDate);
router.put('/attendance/:date', requireRole(policy.recordAttendance), attendanceController.saveForDate);
router.get('/products', resourceController.listProducts);
router.post('/products', manageCatalog, resourceController.createProduct);
router.post('/products/:id/stock', manageCatalog, resourceController.receiveProductStock);
router.post('/products/:id/adjust', manageCatalog, resourceController.adjustProductStock);
router.get('/products/:id/movements', manageCatalog, resourceController.listProductMovements);
router.patch('/products/:id', manageCatalog, resourceController.updateProduct);
router.delete('/products/:id', manageCatalog, resourceController.deleteProduct);
router.get('/services', resourceController.listServices);
router.post('/services', manageCatalog, resourceController.createService);
router.patch('/services/:id', manageCatalog, resourceController.updateService);
router.get('/appointments', appointmentController.list);
router.post('/appointments', appointmentController.create);
router.patch('/appointments/:id', appointmentController.update);
router.delete('/appointments/:id', appointmentController.remove);
router.get('/reports/overview', reportController.overview);
router.get('/reports/archives', reportController.archives);
router.delete('/reports/archives/:id', reportController.deleteArchive);
router.post('/reports/close-day', requireRole(policy.closeDay), reportController.closeDay);
router.post('/reports/close-year', requireRole(policy.closeYear), reportController.closeYear);
router.get('/reports/period', reportController.byPeriod);
router.get('/reports/attendance', reportController.attendance);
router.get('/reports/sales', reportController.sales);
router.get('/reports/cash', requireRole(policy.readHistory), reportController.cash);
router.get('/reports/debts', reportController.debts);
router.get('/reports/team', requireRole(policy.readAnyStaffFinancials), reportController.team);
router.get('/history/days', requireRole(policy.readHistory), operationsController.historyDays);
router.get('/history/days/:day', requireRole(policy.readHistory), operationsController.historyDay);
router.post('/cash/adjustments', requireRole(policy.recordCash), operationsController.createAdjustment);
router.post('/cash/counts', requireRole(policy.recordCash), operationsController.createCount);
router.get('/payroll', requireRole(policy.readAnyStaffFinancials), operationsController.team);
router.get('/payroll/:staffId', requireOwnStaffDataOr(policy.readAnyStaffFinancials), operationsController.member);
router.post('/payroll/:staffId/payouts', requireRole(policy.payCommissions), operationsController.pay);
router.get('/reports/staff/:staffId', requireOwnStaffDataOr(policy.readAnyStaffFinancials), reportController.byStaff);
router.get('/reports/services/:serviceId', reportController.byService);
router.get('/reports/products/:productId', reportController.byProduct);

export default router;
